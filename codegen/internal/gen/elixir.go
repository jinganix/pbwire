package gen

import (
	"fmt"
	"strings"

	"pbwire-codegen/internal/model"

	"google.golang.org/protobuf/reflect/protoreflect"
)

// elixirFiles emits one Elixir file: `elixir-protobuf` modules (the binding's
// schema source: `Pbwire.load_schema/1` consumes `__message_props__/0`).
// No descriptor set is embedded; the modules are the schema, exactly like
// hand-written `protoc-gen-elixir` output, so there is no second file to
// split off. registry=true (default) appends a Registry module holding the
// whole-file module list; register is a no-op (loading is always explicit
// via Pbwire.load_schema/1); model=false leaves the list without modules.
func elixirFiles(f *model.File, opt Options) ([]File, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by protoc-gen-pbwire from %s.\n", f.Path)
	b.WriteString("# elixir-protobuf modules over the Pbwire NIF: load with Pbwire.load_schema/1.\n")
	b.WriteString("# Do not edit; regenerate from the .proto instead.\n\n")
	for _, e := range f.Enums {
		fmt.Fprintf(&b, "# %s\n", e.Full)
		fmt.Fprintf(&b, "defmodule %s do\n", elixirModule(f, e.Name))
		b.WriteString("  @moduledoc false\n")
		fmt.Fprintf(&b, "  use Protobuf, enum: true, syntax: :%s\n\n", f.Syntax)
		for _, v := range e.Values {
			fmt.Fprintf(&b, "  field(:%s, %d)\n", v.Name, v.Number)
		}
		b.WriteString("end\n\n")
	}
	if opt.Model {
		// Oneof declarations precede the fields that reference them.
		for _, m := range f.Messages {
			writeElixirMessage(&b, f, m)
		}
	}
	if opt.Registry {
		writeElixirRegistry(&b, f)
	}
	return []File{{Name: base(f) + ".ex", Content: b.String()}}, nil
}

// writeElixirRegistry appends the whole-file module list: top-level messages
// then enums. Referenced (nested, foreign) modules resolve transitively in
// Pbwire.Schema.build, so callers pass this list straight to load_schema/1.
// The module is per-file (qualified when the file stem differs from the
// package prefix), so two files in one package never share a Registry.
func writeElixirRegistry(b *strings.Builder, f *model.File) {
	reg := elixirModuleFor(f.Package, "Registry")
	if stem, pre := model.Pascal(stem(f.Path)), model.Pascal(f.Package); stem != pre {
		reg = elixirModuleFor(f.Package, stem+".Registry")
	}
	b.WriteString("# Every message in this file, for whole-schema pre-registration.\n")
	fmt.Fprintf(b, "defmodule %s do\n", reg)
	b.WriteString("  @moduledoc false\n")
	b.WriteString("  def message_modules do\n    [\n")
	mods := make([]string, 0, len(f.Messages)+len(f.Enums))
	for _, m := range f.Messages {
		mods = append(mods, elixirModule(f, m.Name))
	}
	for _, e := range f.Enums {
		mods = append(mods, elixirModule(f, e.Name))
	}
	for i, mod := range mods {
		sep := ","
		if i == len(mods)-1 {
			sep = ""
		}
		fmt.Fprintf(b, "      %s%s\n", mod, sep)
	}
	b.WriteString("    ]\n  end\nend\n")
}

// elixirModule maps a local message/enum name to its Elixir alias:
// package tutorial + Person_PhoneNumber -> Tutorial.Person.PhoneNumber.
func elixirModule(f *model.File, local string) string {
	return elixirModuleFor(f.Package, local)
}

// elixirMsg names the module for a message field: the defining file's
// package when foreign (Elixir aliases are global, so no import line),
// this file's own otherwise.
func elixirMsg(f *model.File, field model.Field) string {
	if field.Import != "" {
		if imp := findImport(f, field.Import); imp != nil {
			return elixirModuleFor(imp.Package, field.Message)
		}
	}
	return elixirModule(f, field.Message)
}

func elixirModuleFor(pkg, local string) string {
	var parts []string
	for _, p := range strings.Split(pkg, ".") {
		if p == "" {
			continue
		}
		parts = append(parts, model.Pascal(p))
	}
	for _, p := range strings.Split(local, "_") {
		parts = append(parts, p)
	}
	if len(parts) == 0 {
		return "PbwireGen"
	}
	return strings.Join(parts, ".")
}

func elixirType(f *model.File, field model.Field) string {
	if field.Message != "" {
		return elixirMsg(f, field)
	}
	switch field.Kind {
	case protoreflect.Int32Kind:
		return ":int32"
	case protoreflect.Sint32Kind:
		return ":sint32"
	case protoreflect.Sfixed32Kind:
		return ":sfixed32"
	case protoreflect.Int64Kind:
		return ":int64"
	case protoreflect.Sint64Kind:
		return ":sint64"
	case protoreflect.Sfixed64Kind:
		return ":sfixed64"
	case protoreflect.Uint32Kind:
		return ":uint32"
	case protoreflect.Fixed32Kind:
		return ":fixed32"
	case protoreflect.Uint64Kind:
		return ":uint64"
	case protoreflect.Fixed64Kind:
		return ":fixed64"
	case protoreflect.FloatKind:
		return ":float"
	case protoreflect.DoubleKind:
		return ":double"
	case protoreflect.BoolKind:
		return ":bool"
	case protoreflect.StringKind:
		return ":string"
	case protoreflect.BytesKind:
		return ":bytes"
	case protoreflect.EnumKind:
		if field.Enum != "" {
			return elixirModule(f, field.Enum)
		}
		return ":int32"
	default:
		return ":int64"
	}
}

func writeElixirMessage(b *strings.Builder, f *model.File, m model.Message) {
	fmt.Fprintf(b, "# %s\n", m.Full)
	fmt.Fprintf(b, "defmodule %s do\n", elixirModule(f, m.Name))
	b.WriteString("  @moduledoc false\n")
	fmt.Fprintf(b, "  use Protobuf, syntax: :%s\n\n", f.Syntax)
	oneofs := []string{}
	seen := map[string]bool{}
	for _, field := range m.Fields {
		if field.Skip == "" && field.Oneof != "" && !seen[field.Oneof] {
			seen[field.Oneof] = true
			oneofs = append(oneofs, field.Oneof)
		}
	}
	for i, o := range oneofs {
		fmt.Fprintf(b, "  oneof(:%s, %d)\n", o, i)
	}
	if len(oneofs) > 0 {
		b.WriteString("\n")
	}
	oneofIndex := map[string]int{}
	for i, o := range oneofs {
		oneofIndex[o] = i
	}
	for _, field := range m.Fields {
		if field.Skip != "" {
			fmt.Fprintf(b, "  # skipped %s: %s\n", field.Name, field.Skip)
			continue
		}
		opts := []string{}
		switch {
		case field.Repeated:
			opts = append(opts, "repeated: true")
		case field.Required:
			opts = append(opts, "required: true")
		case field.Oneof != "":
			// oneof membership is the presence story; no optional flag.
		case field.Proto3Optional:
			if f.Syntax == "proto3" {
				opts = append(opts, "proto3_optional: true")
			} else {
				opts = append(opts, "optional: true")
			}
		case f.Syntax == "proto2":
			opts = append(opts, "optional: true")
		}
		typ := elixirType(f, field)
		if strings.HasPrefix(typ, ":") {
			opts = append(opts, "type: "+typ)
		} else {
			opts = append(opts, "type: "+typ)
			if field.Enum != "" {
				opts = append(opts, "enum: true")
			}
		}
		if field.Repeated && field.Packed {
			opts = append(opts, "packed: true")
		}
		if field.Oneof != "" {
			opts = append(opts, fmt.Sprintf("oneof: %d", oneofIndex[field.Oneof]))
		}
		fmt.Fprintf(b, "  field(:%s, %d, %s)\n", field.Name, field.Number, strings.Join(opts, ", "))
	}
	b.WriteString("end\n\n")
}
