package gen

import (
	"fmt"
	"strings"

	"pbwire-codegen/internal/model"

	"google.golang.org/protobuf/reflect/protoreflect"
)

// juliaFiles emits one Julia file: generated structs over the Julia ccall runtime
// (runtime/src/Pbwire.jl: from_bytes, encode_dict, decode_dict, to_dict).
// The descriptor set travels embedded, so no .desc file is needed at use
// time. Oneof members are plain Nothings (no wrapper).
func juliaFiles(f *model.File, opt Options) []File {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by protoc-gen-pbwire from %s.\n", f.Path)
	b.WriteString("# Generated structs over the Pbwire ccall runtime: to/from Dict, encode/decode.\n")
	b.WriteString("# Do not edit; regenerate from the .proto instead.\n\n")
	b.WriteString("import Base64: base64decode\n")
	b.WriteString("push!(LOAD_PATH, joinpath(@__DIR__, \"..\", \"runtime\", \"src\"))\n")
	b.WriteString("using Pbwire\n\n")
	fmt.Fprintf(&b, "const _DESC = base64decode(%q)\n\n", opt.DescSetB64)
	b.WriteString("const _SCHEMA = Ref{Any}(nothing)\n")
	b.WriteString("function _schema()\n")
	b.WriteString("    if _SCHEMA[] === nothing\n")
	b.WriteString("        _SCHEMA[] = Pbwire.from_bytes(Vector{UInt8}(_DESC))\n")
	b.WriteString("    end\n")
	b.WriteString("    return _SCHEMA[]\n")
	b.WriteString("end\n\n")
	for _, e := range f.Enums {
		fmt.Fprintf(&b, "# %s\n", e.Full)
		b.WriteString("module " + className(f, e.Name) + "\n")
		for _, v := range e.Values {
			fmt.Fprintf(&b, "    const %s = %d\n", v.Name, v.Number)
		}
		b.WriteString("end\n\n")
	}
	for _, m := range f.Messages {
		writeJuliaMessage(&b, f, m)
	}
	return []File{{Name: base(f) + "_pbwire.jl", Content: b.String()}}
}

// juliaMsg names the struct for a message field: the owning file's prefix
// when foreign (included files share one namespace, so no import line),
// this file's own otherwise.
func juliaMsg(f *model.File, field model.Field) string {
	if field.Import != "" {
		if imp := findImport(f, field.Import); imp != nil {
			return imp.Prefix + "_" + field.Message
		}
	}
	return className(f, field.Message)
}

func juliaType(f *model.File, field model.Field) string {
	if field.Message != "" {
		return juliaMsg(f, field)
	}
	// Every integer kind and enums decode as Int64 raw bits and encode
	// from any Integer, so the generated structs store Int64 throughout.
	switch field.Kind {
	case protoreflect.BoolKind:
		return "Bool"
	case protoreflect.FloatKind:
		return "Float32"
	case protoreflect.DoubleKind:
		return "Float64"
	case protoreflect.StringKind:
		return "String"
	case protoreflect.BytesKind:
		return "Vector{UInt8}"
	default:
		return "Int64"
	}
}

func juliaFieldType(f *model.File, field model.Field) string {
	t := juliaType(f, field)
	if field.Repeated {
		return "Vector{" + t + "}"
	}
	if field.Message != "" || field.NeedsHas {
		return "Union{Nothing," + t + "}"
	}
	return t
}

func juliaDefault(f *model.File, field model.Field) string {
	if field.Repeated {
		return juliaFieldType(f, field) + "()"
	}
	if field.Message != "" || field.NeedsHas {
		return "nothing"
	}
	switch juliaType(f, field) {
	case "Bool":
		return "false"
	case "String":
		return "\"\""
	case "Vector{UInt8}":
		return "UInt8[]"
	case "Float32", "Float64":
		return "0.0"
	default:
		return "0"
	}
}

func writeJuliaMessage(b *strings.Builder, f *model.File, m model.Message) {
	cls := className(f, m.Name)
	fmt.Fprintf(b, "# %s\n", m.Full)
	fmt.Fprintf(b, "mutable struct %s\n", cls)
	for _, field := range m.Fields {
		if field.Skip != "" {
			fmt.Fprintf(b, "    # skipped %s: %s\n", field.Name, field.Skip)
			continue
		}
		fmt.Fprintf(b, "    %s::%s\n", field.Name, juliaFieldType(f, field))
	}
	b.WriteString("end\n\n")
	fmt.Fprintf(b, "function %s(; kwargs...)\n", cls)
	fmt.Fprintf(b, "    out = %s(\n", cls)
	for _, field := range m.Fields {
		if field.Skip != "" {
			continue
		}
		fmt.Fprintf(b, "        %s,\n", juliaDefault(f, field))
	}
	b.WriteString("    )\n")
	b.WriteString("    for (k, v) in kwargs\n")
	fmt.Fprintf(b, "        setfield!(out, k, v)\n")
	b.WriteString("    end\n")
	b.WriteString("    return out\n")
	b.WriteString("end\n\n")
	// to_dict: struct -> Dict.
	fmt.Fprintf(b, "function to_dict(m::%s)\n", cls)
	b.WriteString("    d = Dict{String,Any}()\n")
	for _, field := range m.Fields {
		if field.Skip != "" {
			continue
		}
		writeJuliaToDict(b, f, field)
	}
	b.WriteString("    return d\n")
	b.WriteString("end\n\n")
	// from_dict: Dict -> struct.
	fmt.Fprintf(b, "function from_dict(::Type{%s}, d::AbstractDict)\n", cls)
	fmt.Fprintf(b, "    out = %s()\n", cls)
	for _, field := range m.Fields {
		if field.Skip != "" {
			continue
		}
		writeJuliaFromDict(b, f, field)
	}
	b.WriteString("    return out\n")
	b.WriteString("end\n\n")
	fmt.Fprintf(b, "function encode(m::%s)\n", cls)
	fmt.Fprintf(b, "    ty = Pbwire.msgtype(_schema(), %q)\n", m.Full)
	b.WriteString("    return Pbwire.encode_dict(ty, to_dict(m))\n")
	b.WriteString("end\n\n")
	fmt.Fprintf(b, "function decode(::Type{%s}, wire::Vector{UInt8})\n", cls)
	fmt.Fprintf(b, "    ty = Pbwire.msgtype(_schema(), %q)\n", m.Full)
	fmt.Fprintf(b, "    return from_dict(%s, Pbwire.decode_dict(ty, wire))\n", cls)
	b.WriteString("end\n\n")
}

func writeJuliaToDict(b *strings.Builder, f *model.File, field model.Field) {
	name := field.Name
	switch {
	case field.Message != "" && !field.Repeated:
		fmt.Fprintf(b, "    if m.%s !== nothing\n", name)
		fmt.Fprintf(b, "        d[%q] = to_dict(m.%s)\n", name, name)
		b.WriteString("    end\n")
	case field.Message != "" && field.Repeated:
		fmt.Fprintf(b, "    if !isempty(m.%s)\n", name)
		fmt.Fprintf(b, "        d[%q] = [to_dict(x) for x in m.%s]\n", name, name)
		b.WriteString("    end\n")
	case field.Repeated:
		fmt.Fprintf(b, "    if !isempty(m.%s)\n", name)
		fmt.Fprintf(b, "        d[%q] = collect(m.%s)\n", name, name)
		b.WriteString("    end\n")
	case field.NeedsHas:
		fmt.Fprintf(b, "    if m.%s !== nothing\n", name)
		fmt.Fprintf(b, "        d[%q] = m.%s\n", name, name)
		b.WriteString("    end\n")
	case juliaType(f, field) == "Bool":
		fmt.Fprintf(b, "    if m.%s\n", name)
		fmt.Fprintf(b, "        d[%q] = true\n", name)
		b.WriteString("    end\n")
	case juliaType(f, field) == "String":
		fmt.Fprintf(b, "    if !isempty(m.%s)\n", name)
		fmt.Fprintf(b, "        d[%q] = m.%s\n", name, name)
		b.WriteString("    end\n")
	default:
		fmt.Fprintf(b, "    if m.%s != 0\n", name)
		fmt.Fprintf(b, "        d[%q] = m.%s\n", name, name)
		b.WriteString("    end\n")
	}
}

func writeJuliaFromDict(b *strings.Builder, f *model.File, field model.Field) {
	name := field.Name
	switch {
	case field.Message != "" && !field.Repeated:
		sub := juliaMsg(f, field)
		fmt.Fprintf(b, "    if haskey(d, %q)\n", name)
		fmt.Fprintf(b, "        out.%s = from_dict(%s, d[%q])\n", name, sub, name)
		b.WriteString("    end\n")
	case field.Message != "" && field.Repeated:
		sub := juliaMsg(f, field)
		fmt.Fprintf(b, "    if haskey(d, %q)\n", name)
		fmt.Fprintf(b, "        out.%s = [from_dict(%s, x) for x in d[%q]]\n", name, sub, name)
		b.WriteString("    end\n")
	case field.Repeated:
		t := juliaType(f, field)
		fmt.Fprintf(b, "    if haskey(d, %q)\n", name)
		fmt.Fprintf(b, "        out.%s = Vector{%s}(d[%q])\n", name, t, name)
		b.WriteString("    end\n")
	default:
		fmt.Fprintf(b, "    if haskey(d, %q)\n", name)
		fmt.Fprintf(b, "        out.%s = d[%q]\n", name, name)
		b.WriteString("    end\n")
	}
}
