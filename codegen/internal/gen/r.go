package gen

import (
	"encoding/base64"
	"fmt"
	"strings"

	"pbwire-codegen/internal/model"
)

// rFiles emits one R file: named-list constructors plus encode/decode over
// the R C-extension runtime (runtime/R/pbwire.R: pbwire_load_raw,
// pbwire_encode, pbwire_decode). The descriptor set travels embedded as a raw
// vector, so no .desc file is needed at use time.
func rFiles(f *model.File, opt Options) []File {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by protoc-gen-pbwire from %s.\n", f.Path)
	b.WriteString("# Named lists over the pbwire R runtime: constructors, encode/decode.\n")
	b.WriteString("# Do not edit; regenerate from the .proto instead.\n\n")
	b.WriteString(".pbwire_schema <- NULL\n")
	b.WriteString(".pbwire_get_schema <- function() {\n")
	b.WriteString("  if (is.null(.pbwire_schema)) {\n")
	b.WriteString("    .pbwire_schema <<- pbwire_load_raw(.pbwire_desc)\n")
	b.WriteString("  }\n")
	b.WriteString("  .pbwire_schema\n")
	b.WriteString("}\n\n")
	raw, _ := base64.StdEncoding.DecodeString(opt.DescSetB64)
	b.WriteString(".pbwire_desc <- as.raw(c(\n")
	for i, v := range raw {
		if i%12 == 0 {
			b.WriteString("  ")
		}
		fmt.Fprintf(&b, "0x%02x", v)
		if i+1 < len(raw) {
			b.WriteString(",")
		}
		if i%12 == 11 || i+1 == len(raw) {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("))\n\n")
	for _, e := range f.Enums {
		fmt.Fprintf(&b, "# %s\n", e.Full)
		for _, v := range e.Values {
			fmt.Fprintf(&b, "%s_%s <- %dL\n", className(f, e.Name), v.Name, v.Number)
		}
		b.WriteString("\n")
	}
	for _, m := range f.Messages {
		writeRMessage(&b, f, m)
	}
	return []File{{Name: base(f) + "_pbwire.R", Content: b.String()}}
}

// rProp is the R list name; leading underscores and digits are not
// valid after `$`, so they move behind an `f_` prefix.
func rProp(field model.Field) string {
	name := field.Name
	if name == "" {
		return "f_"
	}
	c := name[0]
	if c == '_' || (c >= '0' && c <= '9') {
		return "f_" + name
	}
	switch name {
	case "if", "for", "function", "in", "next", "break", "repeat", "while",
		"TRUE", "FALSE", "NULL", "Inf", "NaN", "NA", "class":
		return "f_" + name
	}
	return name
}

func writeRMessage(b *strings.Builder, f *model.File, m model.Message) {
	cls := className(f, m.Name)
	fmt.Fprintf(b, "# %s\n", m.Full)
	fmt.Fprintf(b, "%s_new <- function(...) {\n", cls)
	b.WriteString("  args <- list(...)\n")
	b.WriteString("  out <- list()\n")
	for _, field := range m.Fields {
		if field.Skip != "" {
			fmt.Fprintf(b, "  # skipped %s: %s\n", field.Name, field.Skip)
			continue
		}
		fmt.Fprintf(b, "  if (!is.null(args$%s)) out$%s <- args$%s\n", rProp(field), rProp(field), rProp(field))
	}
	b.WriteString("  class(out) <- c(\"pbwire\", \"list\")\n")
	b.WriteString("  out\n")
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "%s_encode <- function(msg) {\n", cls)
	fmt.Fprintf(b, "  pbwire_encode(.pbwire_get_schema(), %q, msg)\n", m.Full)
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "%s_decode <- function(wire) {\n", cls)
	fmt.Fprintf(b, "  pbwire_decode(.pbwire_get_schema(), %q, wire)\n", m.Full)
	b.WriteString("}\n\n")
}
