package gen

import (
	"encoding/base64"
	"fmt"
	"strings"

	"pbwire-codegen/internal/model"
)

// rFiles emits one R file: named-list constructors plus encode/decode over
// the R C-extension runtime (runtime/R/pbwire.R: pbwire_load_raw,
// pbwire_encode, pbwire_decode). The descriptor set travels embedded as a raw
// vector, so no .desc file is needed at use time.
func rFiles(f *model.File, opt Options) ([]File, error) {
	// Models and schema part ways: named lists in one file, the embedded
	// descriptor set plus its loader in the other. model=false leaves the
	// schema file for dynamic-only users. Each file gets its own dotted
	// holder: sourcing several generated files no longer shares (and
	// clobbers) one global schema the way the single-file layout did.
	sfx := stem(f.Path)
	var files []File
	if opt.Model {
		var b strings.Builder
		fmt.Fprintf(&b, "# Generated by protoc-gen-pbwire from %s.\n", f.Path)
		b.WriteString("# Named lists over the pbwire R runtime: constructors, encode/decode.\n")
		b.WriteString("# Do not edit; regenerate from the .proto instead.\n\n")
		for _, e := range f.Enums {
			fmt.Fprintf(&b, "# %s\n", e.Full)
			for _, v := range e.Values {
				fmt.Fprintf(&b, "%s_%s <- %dL\n", className(f, e.Name), v.Name, v.Number)
			}
			b.WriteString("\n")
		}
		for _, m := range f.Messages {
			writeRMessage(&b, f, m)
		}
		files = append(files, File{Name: base(f) + "_pbwire.R", Content: b.String()})
	}
	var meta strings.Builder
	writeRMeta(&meta, f, opt, sfx)
	files = append(files, File{Name: base(f) + "_meta.R", Content: meta.String()})
	return files, nil
}

// writeRMeta emits the schema file: the embedded descriptor set plus an
// explicit loader, one holder per file. register=true loads lazily on first
// use (as before); otherwise init_schema_<stem> (embedded bytes) or
// use_schema_<stem> (an external schema) must run first, loudly otherwise.
// registry adds the whole-file message list plus a preload that warms
// every type.
func writeRMeta(b *strings.Builder, f *model.File, opt Options, sfx string) {
	hold := func(name string) string { return ".pbwire_" + name + "_" + sfx }
	fmt.Fprintf(b, "# Generated by protoc-gen-pbwire from %s.\n", f.Path)
	b.WriteString("# Embedded descriptor set plus its loader: the schema side of the generated model.\n")
	b.WriteString("# Do not edit; regenerate from the .proto instead.\n\n")
	raw, _ := base64.StdEncoding.DecodeString(opt.DescSetB64)
	b.WriteString(hold("desc") + " <- as.raw(c(\n")
	for i, v := range raw {
		if i%12 == 0 {
			b.WriteString("  ")
		}
		fmt.Fprintf(b, "0x%02x", v)
		if i+1 < len(raw) {
			b.WriteString(",")
		} else {
			b.WriteString(" ")
		}
		if i%12 == 11 || i+1 == len(raw) {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("))\n\n")
	fmt.Fprintf(b, "%s <- NULL\n", hold("schema"))
	fmt.Fprintf(b, "%s <- function(bytes = %s) {\n", hold("init_schema"), hold("desc"))
	fmt.Fprintf(b, "  %s <<- pbwire_load_raw(bytes)\n", hold("schema"))
	fmt.Fprintf(b, "  %s\n", hold("schema"))
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "%s <- function(schema) {\n", hold("use_schema"))
	fmt.Fprintf(b, "  %s <<- schema\n", hold("schema"))
	b.WriteString("}\n\n")
	if opt.Register {
		fmt.Fprintf(b, "%s <- function() {\n", hold("get_schema"))
		fmt.Fprintf(b, "  if (is.null(%s)) {\n", hold("schema"))
		fmt.Fprintf(b, "    %s()\n", hold("init_schema"))
		fmt.Fprintf(b, "  }\n")
		fmt.Fprintf(b, "  %s\n", hold("schema"))
		b.WriteString("}\n")
	} else {
		fmt.Fprintf(b, "%s <- function() {\n", hold("get_schema"))
		fmt.Fprintf(b, "  if (is.null(%s)) {\n", hold("schema"))
		fmt.Fprintf(b, "    stop(\"call %s() first (generated with register=false)\")\n", hold("init_schema"))
		fmt.Fprintf(b, "  }\n")
		fmt.Fprintf(b, "  %s\n", hold("schema"))
		b.WriteString("}\n")
	}
	if opt.Registry {
		b.WriteString("\n# Every message in this file, for whole-schema pre-registration.\n")
		fmt.Fprintf(b, "%s <- c(\n", hold("message_names"))
		for i, m := range f.Messages {
			sep := ","
			if i == len(f.Messages)-1 {
				sep = ""
			}
			fmt.Fprintf(b, "  %q%s\n", m.Full, sep)
		}
		b.WriteString(")\n\n")
		fmt.Fprintf(b, "%s <- function() {\n", hold("preload"))
		fmt.Fprintf(b, "  s <- %s()\n", hold("get_schema"))
		fmt.Fprintf(b, "  for (n in %s) {\n", hold("message_names"))
		fmt.Fprintf(b, "    pbwire_message(s, n)\n")
		fmt.Fprintf(b, "  }\n")
		fmt.Fprintf(b, "  invisible(%s)\n", hold("message_names"))
		b.WriteString("}\n")
	}
}

// rProp is the R list name; leading underscores and digits are not
// valid after `$`, so they move behind an `f_` prefix.
func rProp(field model.Field) string {
	name := field.Name
	if name == "" {
		return "f_"
	}
	c := name[0]
	if c == '_' || (c >= '0' && c <= '9') {
		return "f_" + name
	}
	switch name {
	case "if", "for", "function", "in", "next", "break", "repeat", "while",
		"TRUE", "FALSE", "NULL", "Inf", "NaN", "NA", "class":
		return "f_" + name
	}
	return name
}

func writeRMessage(b *strings.Builder, f *model.File, m model.Message) {
	cls := className(f, m.Name)
	fmt.Fprintf(b, "# %s\n", m.Full)
	fmt.Fprintf(b, "%s_new <- function(...) {\n", cls)
	b.WriteString("  args <- list(...)\n")
	b.WriteString("  out <- list()\n")
	for _, field := range m.Fields {
		if field.Skip != "" {
			fmt.Fprintf(b, "  # skipped %s: %s\n", field.Name, field.Skip)
			continue
		}
		fmt.Fprintf(b, "  if (!is.null(args$%s)) out$%s <- args$%s\n", rProp(field), rProp(field), rProp(field))
	}
	b.WriteString("  class(out) <- c(\"pbwire\", \"list\")\n")
	b.WriteString("  out\n")
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "%s_encode <- function(msg) {\n", cls)
	fmt.Fprintf(b, "  pbwire_encode(.pbwire_get_schema_%s(), %q, msg)\n", stem(f.Path), m.Full)
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "%s_decode <- function(wire) {\n", cls)
	fmt.Fprintf(b, "  pbwire_decode(.pbwire_get_schema_%s(), %q, wire)\n", stem(f.Path), m.Full)
	b.WriteString("}\n\n")
}
