package gen

import (
	"fmt"
	"strings"

	"pbwire-codegen/internal/model"
)

// clojureFiles emits one Clojure namespace: map constructors plus
// encode/decode over the Clojure interop runtime (runtime/src/pbwire/core.clj:
// load-schema-bytes, message-type, encode, decode). The descriptor set
// travels embedded as base64, so no .desc file is needed at use time.
func clojureFiles(f *model.File, opt Options) ([]File, error) {
	ns := strings.ReplaceAll(strings.ToLower(base(f)), "_", "-")
	// Models and schema part ways: constructors plus encode/decode in one
	// namespace, the embedded descriptor set plus its loader in another.
	// model=false leaves the schema namespace for dynamic-only users.
	var files []File
	if opt.Model {
		var b strings.Builder
		fmt.Fprintf(&b, ";; Generated by protoc-gen-pbwire from %s.\n", f.Path)
		b.WriteString(";; Generated maps over the pbwire Clojure runtime: constructors, encode/decode.\n")
		b.WriteString(";; Do not edit; regenerate from the .proto instead.\n")
		fmt.Fprintf(&b, "(ns %s\n", ns)
		b.WriteString("  (:require [clojure.java.io :as io]\n")
		b.WriteString("            [pbwire.core :as pb]\n")
		fmt.Fprintf(&b, "            [%s-meta :as meta])\n", ns)
		b.WriteString("  (:import (java.util Base64)))\n\n")
		for _, e := range f.Enums {
			fmt.Fprintf(&b, ";; %s\n", e.Full)
			for _, v := range e.Values {
				fmt.Fprintf(&b, "(def %s-%s %d)\n", clojureName(className(f, e.Name)), v.Name, v.Number)
			}
			b.WriteString("\n")
		}
		for _, m := range f.Messages {
			writeClojureMessage(&b, f, m, opt)
		}
		files = append(files, File{Name: base(f) + ".clj", Content: b.String()})
	}
	var meta strings.Builder
	writeClojureMeta(&meta, f, opt, ns)
	files = append(files, File{Name: base(f) + "_meta.clj", Content: meta.String()})
	return files, nil
}

// writeClojureMeta emits the schema namespace: the embedded descriptor set
// plus an explicit loader. register=true loads eagerly (as before);
// otherwise init-schema (embedded bytes by default, external bytes for the
// descriptor mode) must run first, loudly otherwise. registry adds the
// whole-file message list plus a preload that warms every type.
func writeClojureMeta(b *strings.Builder, f *model.File, opt Options, ns string) {
	fmt.Fprintf(b, ";; Generated by protoc-gen-pbwire from %s.\n", f.Path)
	b.WriteString(";; Embedded descriptor set plus its loader: the schema side of the generated model.\n")
	b.WriteString(";; Do not edit; regenerate from the .proto instead.\n")
	fmt.Fprintf(b, "(ns %s-meta\n", ns)
	b.WriteString("  (:require [pbwire.core :as pb])\n")
	b.WriteString("  (:import (java.util Base64)))\n\n")
	b.WriteString("(def ^:private desc-bytes\n")
	b.WriteString("  (.decode (Base64/getDecoder)\n")
	fmt.Fprintf(b, "    %q))\n\n", opt.DescSetB64)
	schemaRef := "schema"
	if opt.Register {
		b.WriteString("(def schema (pb/load-schema-bytes desc-bytes))\n")
	} else {
		schemaRef = "(schema)"
		b.WriteString("(defonce ^:private schema-ref (atom nil))\n\n")
		b.WriteString("(defn init-schema\n")
		b.WriteString("  \"Loads the embedded set, or the given bytes for the descriptor mode.\"\n")
		b.WriteString("  ([] (init-schema desc-bytes))\n")
		b.WriteString("  ([bs] (reset! schema-ref (pb/load-schema-bytes bs)) @schema-ref))\n\n")
		b.WriteString("(defn schema\n")
		b.WriteString("  \"The loaded schema, loudly unless init-schema ran.\"\n")
		b.WriteString("  [] (or @schema-ref (throw (ex-info \"call init-schema first (generated with register=false)\" {}))))\n")
	}
	if opt.Registry {
		b.WriteString("\n(def message-names\n")
		b.WriteString("  \"Every message in this file, for whole-schema pre-registration.\"\n")
		b.WriteString("  [\n")
		for _, m := range f.Messages {
			fmt.Fprintf(b, "   %q\n", m.Full)
		}
		b.WriteString("  ])\n\n")
		b.WriteString("(defn preload\n")
		b.WriteString("  \"Warms every message type, so later calls pay no lookup.\"\n")
		fmt.Fprintf(b, "  [] (doseq [full message-names] (pb/message-type %s full)) message-names)\n", schemaRef)
	}
}

// clojureName turns a generated class name into a kebab namespace prefix.
func clojureName(cls string) string {
	return strings.ReplaceAll(strings.ToLower(cls), "_", "-")
}

func writeClojureMessage(b *strings.Builder, f *model.File, m model.Message, opt Options) {
	cls := className(f, m.Name)
	pre := clojureName(cls)
	fmt.Fprintf(b, ";; %s\n", m.Full)
	if opt.Register {
		fmt.Fprintf(b, "(def %s-type (pb/message-type meta/schema %q))\n\n", pre, m.Full)
		fmt.Fprintf(b, "(defn encode-%s [m] (pb/encode %s-type m))\n\n", pre, pre)
		fmt.Fprintf(b, "(defn decode-%s [wire] (pb/decode %s-type wire))\n\n", pre, pre)
	} else {
		// Without implicit loading the type resolves on first use, loudly
		// unless init-schema ran.
		fmt.Fprintf(b, "(def %s-type (delay (pb/message-type (meta/schema) %q)))\n\n", pre, m.Full)
		fmt.Fprintf(b, "(defn encode-%s [m] (pb/encode @%s-type m))\n\n", pre, pre)
		fmt.Fprintf(b, "(defn decode-%s [wire] (pb/decode @%s-type wire))\n\n", pre, pre)
	}
	_ = cls
	fmt.Fprintf(b, "(defn %s\n", pre)
	fmt.Fprintf(b, "  \"Constructor map for %s; absent optionals stay absent.\"\n", m.Full)
	b.WriteString("  [& {:keys [")
	for _, field := range m.Fields {
		if field.Skip != "" {
			continue
		}
		fmt.Fprintf(b, "%s ", field.Name)
	}
	b.WriteString("]}]\n")
	b.WriteString("  (cond-> {}\n")
	for _, field := range m.Fields {
		if field.Skip != "" {
			continue
		}
		fmt.Fprintf(b, "    (some? %s) (assoc :%s %s)\n", field.Name, field.Name, field.Name)
	}
	b.WriteString("  ))\n\n")
}
