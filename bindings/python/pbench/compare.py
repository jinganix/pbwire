"""Provisional Python pbench: the three arms plus the upb baseline, interleaved.

Not the formal run (`make python-bench` is): this probe interleaves every arm
per round so a drifting machine hits them all equally, and reports the best of
three rounds per cell. It is what the provisional table in README.md is
measured with, and what an A/B probe (`--ab old/new`) compares.

    make python-bind
    python3 bindings/python/pbench/compare.py            # all arms, all tiers
    python3 bindings/python/pbench/compare.py --tier xlarge --rounds 5

Arms, per binding's pbench contract:

    tree   the shipped per-field full task: encode(dict); decode(bytes),
           then one get() per field into a fresh dict (pbench/tree.py)
    shim   one downcall: encode(dict) / decode(bytes).to_dict()
    core   the pure-Python core: encode_object(dict) / decode_object(bytes)
"""

import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))          # pbwire extension
sys.path.insert(0, os.path.join(HERE, "..", "benchmarks", "gen"))  # matrix3_pb2
sys.path.insert(0, HERE)

import payload  # noqa: E402

import pbwire as pbw  # noqa: E402
import core as core_arm  # noqa: E402
import tree as tree_arm  # noqa: E402


def time_it(fn, target=0.2, minimum=0.05):
    """ns per op with the iteration count calibrated to `target` seconds."""
    iterations = 1
    while True:
        start = time.perf_counter()
        for _ in range(iterations):
            fn()
        elapsed = time.perf_counter() - start
        if elapsed >= minimum:
            break
        iterations *= 2
    iterations = max(1, int(target / elapsed * iterations))
    best = float("inf")
    for _ in range(2):
        start = time.perf_counter()
        for _ in range(iterations):
            fn()
        elapsed = time.perf_counter() - start
        best = min(best, elapsed / iterations * 1e9)
    return best


def main(argv):
    rounds = 3
    only = None
    for i, arg in enumerate(argv):
        if arg == "--rounds" and i + 1 < len(argv):
            rounds = int(argv[i + 1])
        if arg == "--tier" and i + 1 < len(argv):
            only = argv[i + 1]

    schema = pbw.Schema.from_file(payload.DESC)
    tree_type = schema.message("structtest.Scalars3")
    baseline = "pb %s" % __import__(
        "google.protobuf.internal.api_implementation",
        fromlist=["api_implementation"]).Type()

    print("provisional pbench: best of %d interleaved rounds" % rounds)
    for label, repeats, want in payload.TIERS:
        if only is not None and label != only:
            continue
        values = payload.scalars3(repeats)
        wire = core_arm.marshal(values)
        assert len(wire) == want, "%s: %d bytes, want %d" % (label, len(wire), want)
        payload.check_fields(core_arm.unmarshal(wire), repeats, label + " core")

        arms = [
            ("pbwire-py-core", core_arm.NAME,
             lambda: core_arm.marshal(values),
             lambda: core_arm.unmarshal(wire)),
            ("pbwire-py-tree", tree_arm.NAME,
             lambda: tree_arm.marshal(values),
             lambda: tree_arm.unmarshal(wire)),
            ("pbwire-py-shim", "pbwire-py-shim",
             lambda: tree_type.encode(values),
             lambda: tree_type.decode(wire).to_dict()),
        ]

        try:
            import matrix3_pb2  # the upb baseline (generated by the Makefile)
            base_type = matrix3_pb2.Scalars3
            base_encode = lambda: base_type.FromString(wire).SerializeToString()
            base_decode = lambda: base_type.FromString(wire)
        except ImportError:
            base_encode = base_decode = None

        best = {}
        for _ in range(rounds):
            for group, name, enc, dec in arms:
                for op, fn in (("encode", enc), ("decode", dec)):
                    if fn is None:
                        continue
                    ns = time_it(fn)
                    key = (name, op)
                    best[key] = min(best.get(key, float("inf")), ns)
            if base_encode is not None:
                best[(baseline, "encode")] = min(best.get((baseline, "encode"), float("inf")),
                                                 time_it(base_encode))
                best[(baseline, "decode")] = min(best.get((baseline, "decode"), float("inf")),
                                                 time_it(base_decode))

        print("\n%s: %d bytes, repeat field x%d" % (label, len(wire), repeats))
        print("  %-16s %-8s %10s %10s" % ("impl", "op", "ns/op", "MB/s"))
        for (name, op), ns in sorted(best.items(), key=lambda kv: (kv[0][1], kv[0][0])):
            print("  %-16s %-8s %10.1f %10.1f" % (name, op, ns, len(wire) / ns * 1e3))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
