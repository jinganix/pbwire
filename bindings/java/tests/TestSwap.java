import java.lang.reflect.Proxy;
import java.util.Arrays;

/**
 * Custom implementations replace generated messages through the OrBuilder
 * interface: no per-class registration encodes (S1), and one
 * registerInterface call swaps decode to the custom Builder (S2, S3).
 */
public final class TestSwap {
    private TestSwap() {
    }

    /** Hand-written message: the same two getters, no generated code. */
    static final class MiniInner implements Structtest_Inner3OrBuilder {
        private final String name;
        private final int value;

        MiniInner(MiniBuilder b) {
            name = b.name == null ? "" : b.name;
            value = b.value;
        }

        @Override
        public String getName() {
            return name;
        }

        @Override
        public int getValue() {
            return value;
        }
    }

    /** Hand-written Builder: implements the read interface, decodes into MiniInner. */
    static final class MiniBuilder implements Structtest_Inner3OrBuilder {
        private String name;
        private int value;

        @Override
        public String getName() {
            return name == null ? "" : name;
        }

        public MiniBuilder setName(String v) {
            name = v;
            return this;
        }

        @Override
        public int getValue() {
            return value;
        }

        public MiniBuilder setValue(int v) {
            value = v;
            return this;
        }

        public MiniInner build() {
            return new MiniInner(this);
        }
    }

    // Same rows as the generated table, bound to the custom Builder.
    static final Meta<Structtest_Inner3OrBuilder, MiniBuilder> MINI_META = new Meta<>(
            "structtest.Inner3",
            new FieldMeta[] {
                FieldMeta.ofString(1, Structtest_Inner3OrBuilder::getName, (MiniBuilder b, String v) -> b.setName(v), null, null, false, "name"),
                FieldMeta.ofInt(2, Kind.INT32, Structtest_Inner3OrBuilder::getValue, (MiniBuilder b, int v) -> b.setValue(v), null, null, false, "value"),
            });

    public static void main(String[] args) {
        Structtest_Inner3 gen = Structtest_Inner3.newBuilder().setName("x").setValue(7).build();
        byte[] reference = gen.toByteArray();

        // S1: an unregistered implementation encodes through the interface.
        Object proxy = Proxy.newProxyInstance(TestSwap.class.getClassLoader(),
                new Class<?>[] {Structtest_Inner3OrBuilder.class},
                (p, m, a) -> m.invoke(gen, a));
        check(Arrays.equals(PbCodec.encode((Structtest_Inner3OrBuilder) proxy), reference),
                "S1 proxy != generated bytes");

        // S2: one call swaps interface decode to the custom Builder.
        PbCodec.registerInterface(Structtest_Inner3OrBuilder.class, MINI_META,
                MiniBuilder::new, MiniBuilder::build);
        Structtest_Inner3OrBuilder back =
                PbCodec.parseFrom(reference, Structtest_Inner3OrBuilder.class);
        check(back instanceof MiniInner, "S2 decoded into " + back.getClass());
        check(back.getName().equals("x") && back.getValue() == 7, "S2 values");
        check(Arrays.equals(PbCodec.encode(back), reference), "S2 custom roundtrip");

        // S3: a per-class registration decodes straight into the custom type.
        PbCodec.register(MiniInner.class, MINI_META, MiniBuilder::new, MiniBuilder::build);
        MiniInner direct = PbCodec.parseFrom(reference, MiniInner.class);
        check(direct.getName().equals("x") && direct.getValue() == 7, "S3 values");

        System.out.println("TestSwap: 4 checks passed");
    }

    private static void check(boolean ok, String what) {
        if (!ok) {
            throw new AssertionError(what);
        }
    }
}
